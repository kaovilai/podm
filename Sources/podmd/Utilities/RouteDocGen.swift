import Foundation
import Vapor

/// Renders the route-support surface into documentation artifacts:
/// - `route-coverage.md` — the README section (markdown table)
/// - `index.html` — the GitHub Pages site
///
/// Driven by `podmd --docgen <dir>` from CI, so the published surface can
/// never drift from the registered one: the input is the same
/// `RouteRegistry.bootstrap` enumeration the conformance test enforces, and
/// the reasons come from the same `RouteSupportManifest`.
enum RouteDocGen {
    struct RouteRow: Sendable {
        let method: String
        let pattern: String
        let dialect: String
        let supported: Bool
        let reason: String
    }

    static func rows(for routes: [(method: HTTPMethod, pattern: String)]) -> [RouteRow] {
        routes
            .map { route in
                let key = "\(route.method) \(route.pattern)"
                let isStub = RouteSupportManifest.stubKeys.contains(key)
                let dialect = route.pattern.hasPrefix("/libpod") ? "libpod" : "docker"
                return RouteRow(
                    method: route.method.string,
                    pattern: route.pattern,
                    dialect: dialect,
                    supported: !isStub,
                    reason: RouteSupportManifest.reason(for: key) ?? ""
                )
            }
            .sorted { lhs, rhs in
                (lhs.dialect, lhs.pattern, lhs.method) < (rhs.dialect, rhs.pattern, rhs.method)
            }
    }

    /// The README section body — a summary line plus the full table. CI splices
    /// this between the README's route-coverage markers.
    static func markdown(_ rows: [RouteRow], generatedAt: Date = Date()) -> String {
        let supported = rows.filter(\.supported).count
        let stubs = rows.count - supported
        var out = """
            <!-- Generated by `podmd --docgen` in CI — edits between the markers are
                 overwritten on the next run. Regenerate locally with:
                 swift build && .build/debug/podmd --docgen /tmp/podm-docs -->

            \(rows.count) routes registered (\(supported) supported, \(stubs) deliberately not
            implemented — every gap carries its reason and its tracking context in
            [RouteSupportManifest.swift](Sources/podmd/Utilities/RouteSupportManifest.swift)).
            Full, searchable version: **[podm route coverage site](https://github.tig.pw/podm/)**.

            | Status | Method | Route | Dialect | Reason |
            |---|---|---|---|---|

            """
        for row in rows {
            let status = row.supported ? "✅" : "🚫"
            let reason = row.reason.isEmpty ? "" : row.reason.replacingOccurrences(of: "|", with: "\\|")
            out += "| \(status) | `\(row.method)` | `\(row.pattern)` | \(row.dialect) | \(reason) |\n"
        }
        let formatter = ISO8601DateFormatter()
        out += "\n_Generated \(formatter.string(from: generatedAt)) by the docs workflow._\n"
        return out
    }

    static func write(to directory: String, routes: [(method: HTTPMethod, pattern: String)]) throws {
        let rows = self.rows(for: routes)
        let dir = URL(fileURLWithPath: directory)
        try FileManager.default.createDirectory(at: dir, withIntermediateDirectories: true)

        try markdown(rows)
            .data(using: .utf8)!
            .write(to: dir.appendingPathComponent("route-coverage.md"))
        try html(rows)
            .data(using: .utf8)!
            .write(to: dir.appendingPathComponent("index.html"))
        print("podmd docgen: \(rows.count) routes → \(dir.path)")
    }

    // MARK: - Site

