    private static func jsonData(_ rows: [RouteRow]) -> String {
        func jsonString(_ s: String) -> String {
            let data = try! JSONEncoder().encode(s)
            return String(data: data, encoding: .utf8)!
        }
        let items = rows.map { row in
            "{\"m\":\(jsonString(row.method)),\"p\":\(jsonString(row.pattern)),\"d\":\(jsonString(row.dialect)),\"s\":\(row.supported),\"r\":\(jsonString(row.reason))}"
        }
        return "[\n" + items.joined(separator: ",\n") + "\n]"
    }
